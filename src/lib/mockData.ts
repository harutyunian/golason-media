function createPlayer(
  id: string,
  fotmobId: number,
  nameRu: string,
  nameEn: string,
  number: number,
  position: LineupPlayer['position'],
  x: number,
  y: number,
  options: Partial<Omit<LineupPlayer, 'id' | 'fotmobId' | 'name' | 'number' | 'position' | 'x' | 'y' | 'photoUrl'>> = {}
): LineupPlayer {
  return {
    id,
    fotmobId,
    name: { ru: nameRu, en: nameEn },
    number,
    position,
    x,
    y,
    photoUrl: getFotmobPlayerImage(fotmobId),
    ...options,
  };
}

